"""Generates ObjectRegistry.kt from the FT5AB firmware's object table.

The meter lists every COSEM object it serves in `xdlms.c g_ist[]`, one line
per object: `CL_xxx,{a,b,c,d,e},/* n: name */` (OBIS with F = 255 implied).
CL_xxx indexes `g_cls[]`, which gives the interface class and version.

Usage (from the repo root):
    python tools/gen_object_registry.py
"""
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
SOURCE = ROOT / "app/sampledata/BLref/xdlms.c"
TARGET = ROOT / "app/src/main/java/com/example/meterlinkind/data/protocol/ObjectRegistry.kt"

# CL_xxx -> (class id, version), from g_cls[] in the same file.
CLASSES = {
    "CL_DAT": (1, 0), "CL_REG0": (3, 0), "CL_REG1": (3, 0), "CL_EXR0": (4, 0), "CL_EXR1": (4, 0),
    "CL_PRG0": (7, 1), "CL_PRG1": (7, 1), "CL_PRG2": (7, 1), "CL_CLK": (8, 0), "CL_SCR": (9, 0),
    "CL_SPD": (11, 1), "CL_ASL0": (15, 1), "CL_ASL1": (15, 1), "CL_IMG": (18, 0), "CL_OPT": (19, 1),
    "CL_CAL": (20, 0), "CL_SNG": (22, 0), "CL_HDL": (23, 1), "CL_PSH": (40, 0), "CL_TCP": (41, 0),
    "CL_GPRS": (45, 0), "CL_IPV6": (48, 0), "CL_SEC0": (64, 0), "CL_SEC1": (64, 0), "CL_DIS": (70, 0),
    "CL_LMT": (71, 0),
}

# IS 15959 names, which Gurux also shows, used instead of the firmware's comment.
# Only Profile Generic objects for now; the firmware's own name is noted on each.
# 0.0.99.98.10 (Relay log) and 0.0.99.98.255 (Meter log) keep the firmware names.
IS15959_NAMES = {
    "0.0.94.91.10.255": "Nameplate Profile",              # Name plate detail
    "0.0.99.98.0.255": "Voltage Related Events Profile",   # Event1 profile
    "0.0.99.98.1.255": "Current Related Events Profile",   # Event2 profile
    "0.0.99.98.2.255": "Power Related Events Profile",     # Event3 profile
    "0.0.99.98.3.255": "Transaction Events Profile",       # Event4 profile
    "0.0.99.98.4.255": "Other Tamper Events Profile",      # Event5 profile
    "0.0.99.98.5.255": "Non Roll Over Events Profile",     # Event6 profile
    "0.0.99.98.6.255": "Control Events Profile",           # Event7 profile
    "1.0.94.91.0.255": "Instantaneous Profile",            # Snapshot of instantaneous parameters A1,A14
    "1.0.94.91.3.255": "Scaler: Instantaneous Profile",    # Scaler profile-A1,A14
    "1.0.94.91.4.255": "Scaler: Block Load Profile",       # Scaler profile-A2,A15
    "1.0.94.91.5.255": "Scaler: Daily Load Profile",       # Scaler profile-A3,A16
    "1.0.94.91.6.255": "Scaler: Billing Profile",          # Scaler profile-A4,A17
    "1.0.94.91.7.255": "Scaler: Events Profile",           # Scaler profile-A5-A11
    "1.0.98.1.0.255": "Billing Profile",                   # Billing profile parameters
    "1.0.99.1.0.255": "Block Load Profile",                # Block load profile
    "1.0.99.2.0.255": "Daily Load Profile",                # Daily load profile
}

LINE = re.compile(r"^(CL_\w+),\{([^}]*)\},/\*\s*(\d+):\s*(.*?)\s*\*/")


def main() -> None:
    text = SOURCE.read_bytes().decode("cp932")
    table = text[text.index("INST CONST g_ist[]"):]
    entries = []
    for raw in table.splitlines():
        m = LINE.match(raw.strip())
        if not m or m.group(1) == "CL_SKIP":
            continue
        cls, version = CLASSES[m.group(1)]
        obis = [int(b, 16) for b in m.group(2).split(",")] + [255]
        name = " ".join(m.group(4).replace("　", " ").split()).replace("\\", "\\\\").replace('"', '\\"')
        obis_text = ".".join(map(str, obis))
        name = IS15959_NAMES.get(obis_text, name)
        entries.append((int(m.group(3)), cls, version, obis_text, name))
        if "};" in raw:
            break

    out = [
        "package com.example.meterlinkind.data.protocol",
        "",
        "// GENERATED by tools/gen_object_registry.py from app/sampledata/BLref/xdlms.c (g_ist[]).",
        "// Do not edit by hand; rerun the script when the firmware's object table changes.",
        "// Profile Generic names follow IS 15959 (IS15959_NAMES in the script).",
        "",
        "/** Every COSEM object the FT5AB firmware serves, in `g_ist[]` order. */",
        "object ObjectRegistry {",
        "    val all: List<CosemObject> = listOf(",
    ]
    for index, cls, version, obis, name in entries:
        out.append(f'        CosemObject({index}, {cls}, {version}, ObisCode.parse("{obis}"), "{name}"),')
    out += [
        "    )",
        "",
        "    private val byObis = all.associateBy { it.obis }",
        "",
        "    fun find(obis: ObisCode): CosemObject? = byObis[obis]",
        "",
        "    fun ofClass(classId: Int): List<CosemObject> = all.filter { it.classId == classId }",
        "}",
        "",
    ]
    TARGET.write_text("\n".join(out), encoding="utf-8")
    unused = set(IS15959_NAMES) - {e[3] for e in entries}
    assert not unused, f"IS15959_NAMES for objects the firmware doesn't have: {sorted(unused)}"
    print(f"{len(entries)} objects -> {TARGET.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
